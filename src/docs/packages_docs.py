CREATE_PACKAGE_SUMMARY = "Создание новой посылки"
CREATE_PACKAGE_DESCRIPTION = """
Создаёт новую посылку и ставит задачу на асинхронную обработку.

**Требования:**
- **cookie `session_id`** – для идентификации сессии.
  Если cookie отсутствует или некорректна, она автоматически устанавливается
  и возвращается в заголовке `Set-Cookie` ответа.
- **body** – объект с полями:
  - `name` (str) – наименование посылки
  - `weight` (float) – вес в килограммах
  - `type_id` (int) – ID типа посылки
  - `content_value_usd` (float) – стоимость содержимого в USD

**Возвращает:**
- `str` – UUID созданной посылки.

**Возможные ошибки:**
- `400 Bad Request` – некорректный запрос к базе данных.
- `409 Conflict` – конфликт данных (например, дублирование UUID).
- `500 Internal Server Error` – внутренняя ошибка сервера.
- `503 Service Unavailable` – база данных недоступна.
"""

GET_PACKAGE_BY_UUID_SUMMARY = "Получение посылки по UUID"
GET_PACKAGE_BY_UUID_DESCRIPTION = """
Возвращает информацию о конкретной посылке по её UUID, только если \
    она принадлежит текущей сессии.

**Требования:**
- **cookie `session_id`** – для идентификации сессии.
  Если cookie отсутствует или некорректна, она автоматически устанавливается
  и возвращается в заголовке `Set-Cookie` ответа.
- **path parameter** `package_uuid` (str) – UUID посылки.

**Возвращает:**
- `PackageRead` – объект с данными посылки:
  - `uuid` (str) – UUID посылки
  - `session_id` (str) – ID сессии
  - `name` (str) – наименование
  - `weight` (float) – вес
  - `type_id` (int) – тип посылки
  - `content_value_usd` (float) – стоимость содержимого в USD
  - `delivery_cost_rub` (float | None) – рассчитанная стоимость в RUB \
    (или `null`, если не рассчитана)

**Возможные ошибки:**
- `400 Bad Request` – некорректный запрос к базе данных.
- `404 Not Found` – посылка с указанным UUID не найдена или не \
    принадлежит текущей сессии.
- `500 Internal Server Error` – внутренняя ошибка сервера.
- `503 Service Unavailable` – база данных недоступна.
"""

